def section_56b() -> None:
    dirty = read_dirty()
    qty = pd.to_numeric(dirty["quantity"], errors="coerce")
    price = pd.to_numeric(dirty["unit_price"], errors="coerce")
    disc = pd.to_numeric(dirty["discount_pct"], errors="coerce")
    rev = pd.to_numeric(dirty["revenue"], errors="coerce")

    rules = {
        "order_date parses": pd.to_datetime(
            dirty["order_date"], errors="coerce", format="%Y-%m-%d"
        ).notna(),
        "revenue = qty*price*(1-disc/100)": (
            rev - (qty * price * (1 - disc.fillna(0) / 100))
        ).abs() <= 0.01,
    }
    critical = {"order_date parses"}

    try:
        for name, mask in rules.items():
            failures = int((~mask.eq(True)).sum())
            if name in critical and failures:
                raise ValueError(f"pipeline blocked: {name} has {failures} failures")
            print(f"ok: {name} ({failures} failures)")
    except ValueError as exc:
        print(exc)


