def section_511() -> None:
    orders = read_orders()
    # 1. candidate key hunt
    n = len(orders)
    keys = [c for c in orders.columns if orders[c].nunique(dropna=True) == n]
    show("single-column unique keys", keys)

    # 2. business-key duplicates
    dup = orders.duplicated(subset=["order_id", "product_id"], keep=False)
    show("business-key duplicate lines", int(dup.sum()))

    # 3. missingness ranking
    show("missingness ranking", orders.isna().mean().sort_values(ascending=False).head(3).round(4).to_dict())

    # 4. modified z-score on revenue
    rev = pd.to_numeric(orders["revenue"], errors="coerce")
    med = float(rev.median())
    mad = float((rev - med).abs().median())
    mz = 0.6745 * (rev - med) / mad
    show("modified z-score outliers", {"median": round(med, 2), "mad": round(mad, 2), "flags_gt_3.5": int((mz.abs() > 3.5).sum())})

    # 5. cross-field mask: discount>0 but revenue == full price
    price = pd.to_numeric(orders["unit_price"], errors="coerce")
    qty = pd.to_numeric(orders["quantity"], errors="coerce")
    disc = pd.to_numeric(orders["discount_pct"], errors="coerce")
    full = (qty * price).round(2)
    check = (disc > 0) & (rev.round(2) == full)
    show("discount set but price undiscounted", int(check.sum()))

    # 6. date gap detection
    parsed = pd.to_datetime(orders["order_date"], errors="coerce", format="%Y-%m-%d")
    days = parsed.dropna().dt.normalize().drop_duplicates().sort_values()
    gaps = days.diff().dt.days
    show("date span and largest gap", {"span_days": int((days.max() - days.min()).days), "distinct_days": int(days.nunique()), "largest_gap_days": int(gaps.max())})

    # 7. category case/whitespace scan
    raw_cats = orders["category"].dropna().unique().tolist()
    normalized = sorted({c.strip().lower() for c in raw_cats})
    show("category normalization", {"raw_levels": raw_cats, "normalized_levels": normalized})

    # 8. control total
    show("control total", {"orders": int(orders["order_id"].nunique()), "lines": n, "gross": round(float(rev.sum()), 2)})

    # 9. reconcile counting
    show("gross by channel", pd.to_numeric(orders["revenue"], errors="coerce").groupby(orders["channel"]).sum().round(2).to_dict())

    # 10. duplicate business key with conflicting values
    d = orders[orders.duplicated(subset=["order_id", "product_id"], keep=False)]
    spread = d.groupby(["order_id", "product_id"])["revenue"].nunique()
    show("duplicate keys with conflicting revenue", int((spread > 1).sum()))

    # 11. sentinel scan across all columns
    na_like = {"", "N/A", "-1", "unknown", "9999", "1900-01-01"}
    hits = {c: int(orders[c].isin(list(na_like)).sum()) for c in orders.columns}
    show("sentinel hits", {k: v for k, v in hits.items() if v})


