# ----------------------------------------------------- 5.6 validation rules
def section_56() -> None:
    dirty = read_dirty()
    rules = []

    def check(name: str, mask: pd.Series) -> None:
        mask = mask.eq(True)
        failures = int((~mask).sum())
        rules.append({"rule": name, "checks": int(len(mask)), "failures": failures})

    check("channel in domain", dirty["channel"].isin(["Web", "App", "Phone"]))
    check("region in domain or null", dirty["region"].isna() | dirty["region"].isin(["Midwest", "Northeast", "South", "West"]))
    check("category in domain", dirty["category"].isin(["Camping", "Footwear", "Apparel", "Accessories"]))
    qty = pd.to_numeric(dirty["quantity"], errors="coerce")
    price = pd.to_numeric(dirty["unit_price"], errors="coerce")
    disc = pd.to_numeric(dirty["discount_pct"], errors="coerce")
    ret = pd.to_numeric(dirty["returned"], errors="coerce")
    ship = pd.to_numeric(dirty["shipping_cost"], errors="coerce")
    rev = pd.to_numeric(dirty["revenue"], errors="coerce")
    check("quantity 1-8", qty.between(1, 8))
    check("unit_price > 0", price > 0)
    check("discount_pct 0-100", disc.between(0, 100))
    check("returned in {0,1}", ret.isin([0, 1]))
    check("shipping_cost >= 0", ship >= 0)
    check("revenue >= 0", rev >= 0)
    check("order_id matches ^O-\\d{6}$", dirty["order_id"].str.fullmatch(r"O-\d{6}"))
    check("customer_id matches ^C-\\d{6}$", dirty["customer_id"].str.fullmatch(r"C-\d{6}"))
    check("order_date parses", pd.to_datetime(dirty["order_date"], errors="coerce", format="%Y-%m-%d").notna())
    check("order_date not in future", pd.to_datetime(dirty["order_date"], errors="coerce", format="%Y-%m-%d") <= pd.Timestamp("2026-04-02"))
    check("revenue = qty*price*(1-disc/100)", (rev - (qty * price * (1 - disc.fillna(0) / 100))).abs() <= 0.01)
    check("store_id matches ^S-\\d{2}$", dirty["store_id"].str.fullmatch(r"S-\d{2}"))
    check("no non-breaking space in region", ~dirty["region"].fillna("").str.contains("\u00a0"))
    result = pd.DataFrame(rules)
    result["status"] = np.where(result["failures"] == 0, "PASS", "FAIL")
    show("validation rule runner", result.to_string(index=False))
    show("summary", {"rules": len(result), "passed": int((result["status"] == "PASS").sum()), "failed": int((result["status"] == "FAIL").sum())})

    # export the cross-field offenders
    bad = dirty.loc[((rev - (qty * price * (1 - disc.fillna(0) / 100))).abs() > 0.01), ["order_id", "quantity", "unit_price", "discount_pct", "revenue"]]
    show("cross-field violations", bad.to_string(index=False))


