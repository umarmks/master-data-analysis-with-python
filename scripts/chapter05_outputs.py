# ------------------------------------------------- 5.8 reconciliation
def section_58() -> None:
    con = sqlite3.connect(RAW / "kestrel.db")
    db_rows = pd.read_sql("SELECT COUNT(*) AS n, ROUND(SUM(revenue),2) AS gross FROM orders", con).iloc[0]
    con.close()

    csv = read_orders()
    n = len(csv)
    exact_dupes = int(csv.duplicated().sum())
    parsed = pd.to_datetime(csv["order_date"], errors="coerce", format="%Y-%m-%d")
    bad_dates = int(parsed.isna().sum())
    csv_gross = round(pd.to_numeric(csv["revenue"], errors="coerce").sum(), 2)
    recon = pd.DataFrame(
        [
            ("rows", n, int(db_rows["n"]), n - int(db_rows["n"])),
            ("gross revenue", csv_gross, float(db_rows["gross"]), round(csv_gross - float(db_rows["gross"]), 2)),
        ],
        columns=["metric", "orders_csv", "orders_db", "difference"],
    )
    show("row/sum reconciliation (CSV vs DB)", recon.to_string(index=False))
    show("explanation", {"exact duplicate rows removed": exact_dupes, "unparseable dates removed": bad_dates, "sum": exact_dupes + bad_dates})

    # DB gross -> finance net
    con = sqlite3.connect(RAW / "kestrel.db")
    agg = pd.read_sql(
        "SELECT ROUND(SUM(revenue),2) AS gross, ROUND(SUM(revenue*returned),2) AS returns, "
        "ROUND(SUM(shipping_cost),2) AS shipping FROM orders",
        con,
    ).iloc[0]
    con.close()
    finance = pd.read_csv(AUDIT / "finance_monthly_net.csv")
    computed_net = round(float(agg["gross"]) - float(agg["returns"]) - float(agg["shipping"]), 2)
    finance_net = round(float(finance["net_revenue"].sum()), 2)
    bridge = pd.DataFrame(
        [
            ("gross revenue", round(float(agg["gross"]), 2)),
            ("less returned revenue", round(-float(agg["returns"]), 2)),
            ("less shipping", round(-float(agg["shipping"]), 2)),
            ("= computed net", computed_net),
            ("finance net (with adjustment)", finance_net),
            ("unexplained difference", round(finance_net - computed_net, 2)),
        ],
        columns=["line", "amount"],
    )
    show("gross-to-net bridge vs finance", bridge.to_string(index=False))
    show("adjustment note", finance.loc[finance["note"].notna(), ["month", "net_revenue", "note"]].to_string(index=False))

    # distinct-entity reconciliation
    orders = read_orders()
    cust = pd.read_csv(RAW / "kestrel_customers.csv")
    in_orders = set(orders["customer_id"].dropna())
    in_cust = set(cust["customer_id"])
    show("customer reconciliation", {"distinct in orders": len(in_orders), "in dimension": len(in_cust), "orders not in dimension": len(in_orders - in_cust), "in dimension unused": len(in_cust - in_orders)})

    # referential check
    products = pd.read_csv(RAW / "kestrel_products.csv")
    stores = {"S-%02d" % i for i in range(1, 13)}
    show("referential checks", {"bad product_id": int((~orders["product_id"].isin(set(products["product_id"]))).sum()), "bad store_id": int((~orders["store_id"].isin(stores)).sum())})


