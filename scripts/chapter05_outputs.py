def section_53b() -> None:
    orders = read_orders()
    dirty = read_dirty()

    def whitespace_scan(df: pd.DataFrame) -> pd.DataFrame:
        rows = []
        for col in df.columns:
            s = df[col].dropna().astype(str)
            rows.append({
                "column": col,
                "leading_ws": int(s.str.startswith(" ").sum()),
                "trailing_ws": int(s.str.endswith(" ").sum()),
                "non_ascii": int(s.str.contains(r"[^\x00-\x7f]", regex=True).sum()),
            })
        return pd.DataFrame(rows)

    flags = whitespace_scan(orders)
    flags = flags[(flags[["leading_ws", "trailing_ws", "non_ascii"]] > 0).any(axis=1)]
    show("whitespace/encoding flags (clean orders)", flags.to_string(index=False))

    dflags = whitespace_scan(dirty)
    dflags = dflags[(dflags[["leading_ws", "trailing_ws", "non_ascii"]] > 0).any(axis=1)]
