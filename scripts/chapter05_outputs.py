def section_58b() -> None:
    con = sqlite3.connect(RAW / "kestrel.db")
    db_month = pd.read_sql(
        "SELECT substr(order_date,1,7) AS month, COUNT(*) AS rows_db, "
        "ROUND(SUM(revenue),2) AS gross_db FROM orders GROUP BY month",
        con,
    )
    con.close()

    csv = read_orders()
    csv = csv.assign(
        month=pd.to_datetime(csv["order_date"], errors="coerce", format="%Y-%m-%d").dt.strftime("%Y-%m"),
        revenue_num=pd.to_numeric(csv["revenue"], errors="coerce"),
    )
    csv_month = csv.groupby("month").agg(
        rows_csv=("order_id", "size"),
        gross_csv=("revenue_num", lambda s: round(float(s.sum()), 2)),
    ).reset_index()

    comp = csv_month.merge(db_month, on="month", how="outer").fillna(0)
    for c in ["rows_csv", "rows_db"]:
        comp[c] = comp[c].astype(int)
    comp["row_diff"] = comp["rows_csv"] - comp["rows_db"]
    comp["abs_diff"] = comp["row_diff"].abs()
    comp = comp.sort_values("abs_diff", ascending=False).drop(columns="abs_diff")
    show("monthly reconciliation (top 8 by |row diff|)",
         comp.head(8)[["month", "rows_csv", "rows_db", "row_diff", "gross_csv", "gross_db"]].to_string(index=False))
    show("row-diff total", int(comp["row_diff"].sum()))


